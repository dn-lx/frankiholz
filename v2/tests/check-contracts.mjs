import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
assert.ok(fs.existsSync(path.join(root,'public/assets/frankiholz-logo-for-dark.png')));
assert.ok(fs.existsSync(path.join(root,'public/assets/frankiholz-logo-for-light.png')));
assert.ok(fs.existsSync(path.join(root,'public/assets/frankiholz-favicon.svg')));
const booking=read('components/booking-panel.tsx');
const admin=read('components/admin-dashboard.tsx');
for(const rpc of ['frankiholz_get_calendar_rates','frankiholz_estimate_total','frankiholz_create_booking_v2'])assert.ok(booking.includes(rpc),'Missing server authoritative '+rpc);
for(const api of ['frankiholz_admin_access_check','frankiholz_set_payment_environment','frankiholz-booking-decision'])assert.ok(admin.includes(api),'Missing protected '+api);
assert.ok(booking.includes("checkout=blocked"),'Booking must offer blocked checkout boundaries');
assert.ok(booking.includes('isValidEnd'), 'Booking must protect blocked overnight stays');
assert.ok(booking.includes("actual==='live'"),'LIVE preview confirmation required');
assert.ok(read('components/review-carousel.tsx').includes('prefers-reduced-motion')||read('components/review-carousel.tsx').includes('useReducedMotion'));
for(const word of ['STRIPE_SECRET_KEY','SERVICE_ROLE_KEY','STRIPE_TEST_SECRET_KEY'])assert.ok(!read('lib/config.ts').includes(word),'Secret key reference in client');
console.log('v2 static contracts passed');
